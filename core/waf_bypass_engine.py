class WAFBypassEngine:
    @staticmethod
    def detect_waf(headers: Dict[str, str], body: str, cookies: Optional[Dict[str, str]] = None) -> Dict[str, Any]:
        """Analyzes HTTP response headers, body, and cookies to identify WAF signature."""
        headers_lower = {k.lower(): v.lower() for k, v in headers.items()}
        server_val = headers_lower.get("server", "")
        body_lower = body.lower() if body else ""
        cookie_keys = [k.lower() for k in cookies.keys()] if cookies else []

        for waf in WAF_SIGNATURES:
            # 1. Header check
            for h in waf["headers"]:
                if h in headers_lower:
                    return {
                        "detected": True,
                        "waf_name": waf["name"],
                        "vendor": waf["vendor"],
                        "evidence": f"Header match: '{h}'",
                        "bypasses": WAF_BYPASS_TECHNIQUES.get(waf["name"], WAF_BYPASS_TECHNIQUES["Default / Generic WAF"])
                    }

            # 2. Server header check
            for s in waf["server"]:
                if s in server_val:
                    return {
                        "detected": True,
                        "waf_name": waf["name"],
                        "vendor": waf["vendor"],
                        "evidence": f"Server header: '{server_val}'",
                        "bypasses": WAF_BYPASS_TECHNIQUES.get(waf["name"], WAF_BYPASS_TECHNIQUES["Default / Generic WAF"])
                    }

            # 3. Cookie check
            for c in waf["cookie"]:
                if any(re.search(c, ck) for ck in cookie_keys):
                    return {
                        "detected": True,
                        "waf_name": waf["name"],
                        "vendor": waf["vendor"],
                        "evidence": f"Security Cookie match: '{c}'",
                        "bypasses": WAF_BYPASS_TECHNIQUES.get(waf["name"], WAF_BYPASS_TECHNIQUES["Default / Generic WAF"])
                    }

            # 4. Body regex pattern check
            for p in waf["body_patterns"]:
                if re.search(p, body_lower):
                    return {
                        "detected": True,
                        "waf_name": waf["name"],
                        "vendor": waf["vendor"],
                        "evidence": f"Response signature match: '{p}'",
                        "bypasses": WAF_BYPASS_TECHNIQUES.get(waf["name"], WAF_BYPASS_TECHNIQUES["Default / Generic WAF"])
                    }

        return {
            "detected": False,
            "waf_name": "No Active WAF Fingerprinted",
            "vendor": "Direct Origin / Standard Reverse Proxy",
            "evidence": "Standard HTTP headers observed without WAF block signatures.",
            "bypasses": WAF_BYPASS_TECHNIQUES["Default / Generic WAF"]
        }
